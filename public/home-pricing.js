// 여기봐AI 유료 서비스 계획. 현재는 무료 베타이며 구매자 집계가 연결되어 있지 않다.
export const HOME_PRICE_STEPS = Object.freeze([
  Object.freeze({ range: '첫 100명', price: '3,900원' }),
  Object.freeze({ range: '101~1,000명', price: '9,900원' }),
  Object.freeze({ range: '1,001~5,000명', price: '12,900원' }),
  Object.freeze({ range: '5,001~1만 명', price: '19,900원' }),
  Object.freeze({ range: '1만 1명~3만 명', price: '29,900원' }),
  Object.freeze({ range: '3만 1명~10만 명', price: '39,900원' }),
]);
export const FIRST_HOME_PRICE = HOME_PRICE_STEPS[0].price;

export function makeHomePricing(h, focusStart) {
  const feature = (text, pending = false) => h('li', { class: pending ? 'pricing-feature pricing-feature-pending' : 'pricing-feature' },
    h('span', { class: 'pricing-check', 'aria-hidden': 'true' }, '✓'),
    h('span', null, text));
  const levels = HOME_PRICE_STEPS.map((step, i) => h('li', { class: i === 0 ? 'pricing-level pricing-level-first' : 'pricing-level' },
    h('span', { class: 'pricing-level-number' }, `${i + 1}단계${i === 0 ? ' · 예정' : ''}`),
    h('span', { class: 'pricing-level-range' }, step.range),
    h('strong', { class: 'pricing-level-price' }, step.price)));
  return h('section', { class: 'home-pricing', 'aria-labelledby': 'home-pricing-title' },
    h('div', { class: 'pricing-heading' },
      h('p', { class: 'pricing-eyebrow' }, '여기봐AI 가격 안내'),
      h('h2', { id: 'home-pricing-title' }, '가게 소개, 부담 없이 시작하세요'),
      h('p', { class: 'pricing-lead' }, '무료로 만들어 보고, 마음에 들면 우리 가게 페이지를 공개해요.')),
    h('div', { class: 'pricing-beta', role: 'note' },
      h('strong', null, '현재 무료 베타'),
      h('span', null, '지금은 공개 페이지·QR·공유 문구도 무료예요. 아래 가격과 무료·유료 구성은 유료 서비스 도입 후 적용 예정이며, 현재 실제 결제는 운영하지 않아요.')),
    h('div', { class: 'pricing-plans' },
      h('article', { class: 'pricing-plan pricing-free', 'aria-labelledby': 'pricing-free-title' },
        h('p', { class: 'pricing-plan-label' }, '무료'),
        h('h3', { id: 'pricing-free-title' }, '먼저 만들어 보기'),
        h('p', { class: 'pricing-amount' }, '0원'),
        h('p', { class: 'pricing-plan-desc' }, '결제 전에 내용을 직접 보고 결정해요.'),
        h('ul', { class: 'pricing-features' },
          feature('가게 정보 검색 및 직접 확인'),
          feature('AI 소개글·예상 질문과 답변 미리보기'),
          feature('가게에 맞는 키워드 제안'),
          feature('공개 전 내용 직접 수정')),
        h('p', { class: 'pricing-plan-note' }, '유료 전환 후에는 비공개 미리보기로 제공하며, 공개 주소·QR은 유료 공개에 포함될 예정이에요.')),
      h('article', { class: 'pricing-plan pricing-paid', 'aria-labelledby': 'pricing-paid-title' },
        h('p', { class: 'pricing-plan-label' }, '유료 공개 · 도입 예정'),
        h('h3', { id: 'pricing-paid-title' }, '우리 가게 공개하기'),
        h('p', { class: 'pricing-amount' }, FIRST_HOME_PRICE, h('span', null, '첫 100명 예정가')),
        h('p', { class: 'pricing-plan-desc' }, '유료 전환 시 1회 결제 · 월 정기결제 없음'),
        h('ul', { class: 'pricing-features' },
          feature('무료 미리보기 기능 포함'),
          feature('여기봐AI 안에 가게 소개 페이지 공개'),
          feature('공개 주소와 QR 코드'),
          feature('인스타·SNS에 쓸 공유 문구'),
          feature('관리 비밀번호로 내용 수정·삭제'),
          feature('내 가게 AI 검색 봇 접근 현황 (준비중)', true)),
        h('p', { class: 'pricing-plan-note' }, '공개 유지 기간과 이용 조건은 유료 출시 전에 안내할 예정이에요.'))),
    h('section', { class: 'pricing-progress', 'aria-labelledby': 'pricing-progress-title' },
      h('div', { class: 'pricing-progress-heading' },
        h('div', null, h('p', { class: 'pricing-progress-kicker' }, '단계별 공개 가격'),
          h('h3', { id: 'pricing-progress-title' }, '일찍 시작할수록 낮아지는 가격'),
          h('p', null, '유료 전환 후 누적 구매 단계에 따라 가격이 바뀔 예정이에요.')),
        h('div', { class: 'pricing-progress-total' },
          h('span', null, '누적 유료 구매자'),
          h('strong', null, '집계 준비 중'),
          h('small', null, '현재 유료 결제 미운영'))),
      h('p', { class: 'pricing-offer' }, '첫 100명 ', h('strong', null, HOME_PRICE_STEPS[0].price), ' · 다음 단계 ', h('strong', null, HOME_PRICE_STEPS[1].price), ' 예정'),
      h('div', { class: 'pricing-meter', role: 'img', 'aria-label': '유료 구매자 집계가 연결되지 않아 진행률을 표시하지 않아요.' },
        HOME_PRICE_STEPS.map(() => h('span', { class: 'pricing-meter-segment', 'aria-hidden': 'true' }))),
      h('p', { class: 'pricing-meter-note' }, '구매자 수와 단계별 진행률은 결제·집계가 연결된 뒤 표시할 예정이에요.'),
      h('ol', { class: 'pricing-levels' }, levels),
      h('p', { class: 'pricing-progress-note' }, '각 가격은 1회 공개 기준 제안이에요. 구매 인원 산정, 취소·환불 처리와 상세 조건은 유료 출시 전에 안내해요.')),
    h('p', { class: 'pricing-disclaimer' }, 'AI·검색 봇의 접근은 AI 답변의 추천·인용이나 실제 손님 방문을 뜻하지 않아요. 검색 노출과 AI 추천은 보장하지 않아요.'),
    h('button', { class: 'btn primary go pricing-start', type: 'button', onclick: focusStart }, '지금 무료로 페이지 만들기'));
}
