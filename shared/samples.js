const A = (v, s = 'exact', extra = {}) => ({ v, s, ...extra });
const U = () => ({ s: 'unknown' });
const NA = () => ({ s: 'na' });
const L = () => ({ s: 'later' });

function confirmPublicChecks(data) {
  for (const chk of publicInfoChecks(data)) data.answers[chk.id] = { v: 'confirm', sig: chk.sig, s: 'exact' };
  return data;
}

